#!/usr/bin/env python3
"""Write software_versions.yml, provenance.json and methods.md for an nf-codonyat run.

    provenance.py --versions versions.tsv --params params.json --pipeline-version 0.3.0 \
        --checksum reference=ref.fasta --checksum kraken2_db=db_dir ...

versions.tsv: process<TAB>tool<TAB>version (from the Nextflow 'versions' topic).
Research use only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from collections import defaultdict
from datetime import datetime, timezone


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def checksums(label: str, path: str) -> dict:
    if os.path.isdir(path):
        files = sorted(os.path.join(dp, f) for dp, _, fs in os.walk(path, followlinks=True) for f in fs)
        return {f"{label}/{os.path.relpath(f, path)}": sha256(f) for f in files}
    return {label: sha256(path)}


def load_params(path: str) -> dict:
    """params as JSON, or as 'name<TAB>value' lines (as written by the workflow)."""
    text = open(path).read()
    try:
        return json.loads(text)
    except ValueError:
        out: dict = {}
        for line in text.splitlines():
            name, _, value = line.partition("\t")
            if name:
                out[name] = None if value in ("", "null") else value
        return out


def is_true(value) -> bool:
    return str(value).lower() == "true"


METHODS = """# Methods (auto-generated by nf-codonyat {version})

**Research use only.** These outputs are descriptive (QC, contamination report,
read-mapping based subtype estimate, consensus sequence, codon and amino-acid
frequencies). They contain no drug-resistance or clinical interpretation.

FASTQ samples were quality-checked with FastQC {fastqc} and trimmed with fastp {fastp}.
A contamination report was produced with Kraken2 {kraken2} against the database
`{kraken2_db}` (report only; no reads were removed; a warning is raised when HIV-1 is
below {warn_hiv}% of classified fragments or human reads exceed {warn_human}% of all fragments).
An HIV-1 subtype estimate was obtained by competitive read mapping with BBSplit (BBMap {bbmap})
against the panel `{panel}` (bins A, B and group M consensus), reported as the % of reads
assigned unambiguously to each bin (read-mapping based; research use only).
Overlapping read pairs were merged with BBMerge (BBMap {bbmap}); merged reads (single-end)
and unmerged pairs (paired-end) were aligned with Bowtie2 {bowtie2} (`{bowtie2_args}`) to the
annotated reference and combined with samtools {samtools}. Alignments with MAPQ < {min_mapq}
or flags {exclude_flags} were removed. Strand metrics were additionally computed from an alignment
of the unmerged (pre-merge) read pairs. A consensus sequence was called with iVar {ivar}
(threshold {ct}, IUPAC codes for mixtures, minimum depth {cd}x with N below it, minimum base
quality {cq}; insertions at >= {ci}; majority deletions applied). Codon frequencies per protein
({proteins}) were computed with codonyat {codonyat} and summarised as amino-acid frequency tables.
Reports were collated with MultiQC {multiqc}.
"""


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--versions", required=True)
    ap.add_argument("--params", required=True)
    ap.add_argument("--pipeline-version", required=True)
    ap.add_argument("--checksum", action="append", default=[], metavar="LABEL=PATH")
    args = ap.parse_args(argv)

    by_process: dict[str, dict[str, str]] = defaultdict(dict)
    tools: dict[str, list[str]] = defaultdict(list)
    with open(args.versions) as fh:
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 3 and parts[0]:
                by_process[parts[0]][parts[1]] = parts[2]
                if parts[2] not in tools[parts[1]]:
                    tools[parts[1]].append(parts[2])
    with open("software_versions.yml", "w") as fh:
        for proc in sorted(by_process):
            fh.write(f"{proc}:\n")
            for tool, ver in sorted(by_process[proc].items()):
                fh.write(f"    {tool}: \"{ver}\"\n")
        fh.write("Workflow:\n")
        fh.write(f"    nf-codonyat: \"{args.pipeline_version}\"\n")

    params = load_params(args.params)
    sums: dict[str, str] = {}
    for item in args.checksum:
        label, _, path = item.partition("=")
        if path and os.path.exists(path):
            sums.update(checksums(label, path))
    json.dump(
        {
            "pipeline": "sjoclaudi/nf-codonyat",
            "version": args.pipeline_version,
            "generated": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "research_use_only": True,
            "software": {k: " / ".join(sorted(v)) for k, v in sorted(tools.items())},
            "params": params,
            "checksums_sha256": sums,
        },
        open("provenance.json", "w"),
        indent=2,
    )
    t = lambda k: " / ".join(sorted(tools[k])) if tools.get(k) else "n/a"  # noqa: E731
    with open("methods.md", "w") as fh:
        fh.write(METHODS.format(
            version=args.pipeline_version, fastqc=t("fastqc"), fastp=t("fastp"), kraken2=t("kraken2"),
            kraken2_db=os.path.basename(str(params.get("kraken2_db") or "n/a").rstrip("/")),
            warn_hiv=params.get("contamination_warn_hiv_pct"), warn_human=params.get("contamination_warn_human_pct"),
            bbmap=t("bbmap"), panel=os.path.basename(str(params.get("subtype_panel") or "n/a").rstrip("/")),
            bowtie2=t("bowtie2"), bowtie2_args=params.get("bowtie2_args"), samtools=t("samtools"),
            min_mapq=params.get("min_mapq"), exclude_flags=params.get("exclude_flags"), ivar=t("ivar"),
            ct=params.get("consensus_threshold"), cd=params.get("consensus_min_depth"),
            cq=params.get("consensus_min_bq"), ci=params.get("consensus_insertion_threshold"),
            proteins=params.get("protein"), codonyat=t("codonyat"), multiqc=t("multiqc"),
        ))
        notes = []
        if is_true(params.get("skip_contamination")):
            notes.append("The Kraken2 contamination report was skipped (`--skip_contamination`).")
        if is_true(params.get("skip_subtype")):
            notes.append("The subtype estimate was skipped (`--skip_subtype`).")
        if not is_true(params.get("merge_pairs", "true")):
            notes.append("Read pairs were not merged (`--merge_pairs false`); pairs were aligned as pairs and the "
                         "separate strand-metrics alignment was not needed.")
        elif not is_true(params.get("strand_metrics_unmerged", "true")):
            notes.append("Strand metrics from the unmerged read pairs were not computed (`--strand_metrics_unmerged false`).")
        if is_true(params.get("skip_consensus")):
            notes.append("The consensus sequence was not called (`--skip_consensus`).")
        notes.append("Single-end FASTQ samples skip read merging and the strand-metrics alignment. "
                     "SAM inputs enter at the alignment filter; the FASTQ-only steps (FastQC, fastp, Kraken2, "
                     "subtype estimate, merging, Bowtie2) do not apply to them.")
        fh.write("\n## Notes\n\n")
        for note in notes:
            fh.write(f"- {note}\n")
        fh.write("\n## Software versions\n\n")
        for tool in sorted(tools):
            fh.write(f"- {tool} {t(tool)}\n")
        fh.write("\n## Reference data checksums (SHA-256)\n\n")
        for label, digest in sums.items():
            fh.write(f"- `{label}`: `{digest}`\n")


if __name__ == "__main__":
    main()
